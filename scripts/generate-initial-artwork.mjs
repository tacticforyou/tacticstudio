import { readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

// Run npm run artwork:generate after replacing any of these source assets.
// Preserve alpha and recognizable details instead of blurring transparent art.
const previews = {
  "hero-ai-art.webp": 320,
  "services-web-background.webp": 160,
  "shared-portrait-right.webp": 160,
  "shared-portrait.webp": 384,
  "shared-web-phone.webp": 160,
  "team-portrait-center.webp": 96,
  "team-portrait-left.webp": 96,
  "team-portrait-right.webp": 96,
  "years-stars.webp": 256,
};
const assets = new URL("../public/images/landing/", import.meta.url);
const components = new URL("../app/_landing/components/", import.meta.url);
const entries = [];

for (const [name, width] of Object.entries(previews)) {
  const source = await readFile(new URL(name, assets));
  const preview = await sharp(source)
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 75, alphaQuality: 100 })
    .toBuffer();
  entries.push(
    `  ${JSON.stringify(name)}: "data:image/webp;base64,${preview.toString("base64")}",`,
  );
  console.log(`${name}: ${preview.length} preview bytes`);
}

await writeFile(
  new URL("initial-artwork.ts", components),
  `// Generated by npm run artwork:generate. Do not edit by hand.\nexport const initialArtwork: Readonly<Partial<Record<string, \`data:image/\${string}\`>>> = {\n${entries.join("\n")}\n};\n`,
);
